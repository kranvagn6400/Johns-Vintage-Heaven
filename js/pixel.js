  gramophone(seed) {
    const wood = [PX.o, PX.r, PX.t, PX.g][hashNum(seed) % 4];
    const pal = { B: PX.y, D: '#b8860b', L: '#fff2b3', K: PX.ink, W: wood };
    return Object.entries(pal).map(([ch, fill]) => [fill, this.bitmapPath(this.gramoRows, ch)]);
  },
  art(p) {
    return p.kind === 'gramophone' ? this.svg(24, this.gramophone(p.id || p.title)) : this.svg(32, this.record(p.id || p.title));
  }
